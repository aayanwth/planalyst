"""
PLanalyst — Streamlit Page: Model Evaluation

Charts built from the tables in docs/model_evaluation.md (generated by `python -m planalyst.ml.report`),
with the full report and its figures underneath, so the evidence sits next to the forecasts.
"""

import re
from pathlib import Path

import pandas as pd
import streamlit as st

from streamlit_app import charts, theme
from streamlit_app.utils import parse_md_tables, split_report, to_numeric

DOCS = Path(__file__).resolve().parent.parent.parent / "docs"


def _find(tables: list[tuple[str, pd.DataFrame]], predicate) -> pd.DataFrame | None:
    for _, df in tables:
        if predicate(list(df.columns)):
            return to_numeric(df, skip=("model", "A", "B", "metric", "reading", "source", "champion"))
    return None


def render() -> None:
    theme.page_header(
        "Model evaluation",
        "Walk-forward backtest: each season is predicted using only earlier seasons, so no future information leaks into a forecast.",
    )
    report = DOCS / "model_evaluation.md"
    if not report.exists():
        theme.empty_state("No evaluation report yet", "Generate it with `python -m planalyst.ml.report`.")
        return

    text = report.read_text(encoding="utf-8")
    tables = parse_md_tables(text)
    models = _find(tables, lambda c: "model" in c and "log_loss" in c and "rps" in c)
    seasons = _find(tables, lambda c: c[:1] == ["season"] and "prior" in c)
    ece = _find(tables, lambda c: c == ["model", "ECE"])
    champ35 = _find(tables, lambda c: c == ["season", "elo", "poisson", "xgb", "blend"])
    bootstrap = _find(tables, lambda c: "95% CI low" in c)

    matches = re.search(r"\(([\d,]+) matches\)", text)
    span = re.search(r"Test seasons: (\d{4}[–-]\d{4})", text)

    if models is not None:
        prior = models[models["model"] == "prior"].iloc[0]
        blend = models[models["model"] == "blend"].iloc[0]
        theme.stat_strip(
            [
                ("Matches tested", theme.counted(int(matches.group(1).replace(",", ""))) if matches else "n/a", f"seasons {span.group(1) if span else 'n/a'}"),
                ("Improvement on baseline", f"{(prior['log_loss'] - blend['log_loss']) / prior['log_loss']:.1%}", f"baseline {prior['log_loss']:.3f}"),
                ("Results called right", f"{blend['accuracy']:.1%}", f"{prior['accuracy']:.1%} for the baseline"),
            ]
        )

    left, right = st.columns(2, gap="medium")
    with left:
        with theme.panel("Match outcome: log loss by model", "home / draw / away"):
            if models is not None:
                theme.show(charts.dot_plot(models, "model", "log_loss"), key="me-ll")
            else:
                theme.empty_state("Table not found", "The report layout changed; see the full report below.")
    with right:
        with theme.panel("Match outcome: RPS by model", "ranked probability score"):
            if models is not None:
                theme.show(charts.dot_plot(models, "model", "rps"), key="me-rps")
            else:
                theme.empty_state("Table not found", "The report layout changed; see the full report below.")

    left, right = st.columns([7, 5], gap="medium")
    with left:
        with theme.panel("Log loss by test season"):
            if seasons is not None:
                theme.show(charts.season_lines(seasons), key="me-seasons")
            else:
                theme.empty_state("Table not found", "See the full report below.")
    with right:
        with theme.panel("Calibration error", "when it says 60%, is it right 60% of the time?"):
            if ece is not None:
                theme.show(charts.dot_plot(ece, "model", "ECE", height=330, decimals=3), key="me-ece")
            else:
                theme.empty_state("Table not found", "See the full report below.")

    with theme.panel("Title-race backtest", "probability given to the eventual champion at matchweek 35"):
        if champ35 is not None:
            theme.show(charts.champion_heatmap(champ35), key="me-champ")
            st.markdown(
                '<div class="note">One champion per season means six outcomes per checkpoint. '
                "This can expose a broken simulator but cannot rank close alternatives with confidence.</div>",
                unsafe_allow_html=True,
            )
        else:
            theme.empty_state("Table not found", "See the full report below.")

    if bootstrap is not None:
        with theme.panel("Is the difference real?", "paired bootstrap, 2,000 resamples"):
            show = bootstrap.copy()
            st.dataframe(show, hide_index=True, width="stretch", height=360)

    with st.expander("Full report and figures"):
        for kind, content in split_report(text):
            if kind == "markdown":
                st.markdown(content)
            elif (DOCS / content).exists():
                st.image(str(DOCS / content), width="stretch")
