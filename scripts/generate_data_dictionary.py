"""
Generate docs/data_dictionary.md from the dbt schema files (sources, silver, gold models) and
the column lists of the Gold tables that Python writes (predictions, history, fixture
forecasts). Every Python-written column must have a description here, so adding a column
without documenting it fails loudly instead of leaving a gap.

    python scripts/generate_data_dictionary.py          # rewrite the file
    python scripts/generate_data_dictionary.py --check  # exit 1 if it is out of date
"""

import argparse
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "docs" / "data_dictionary.md"
MODELS = ROOT / "dbt_project" / "models"

# Descriptions for columns written by Python (not defined in dbt).
PYTHON_COLUMNS = {
    "team_name": "Canonical team name",
    "win_probability": "Probability of winning the title (share of simulations won)",
    "avg_final_points": "Mean simulated final points",
    "avg_final_rank": "Mean simulated final league position",
    "simulations_won": "Number of simulations in which the team won the title",
    "total_simulations": "Number of simulations run",
    "top4_probability": "Probability of finishing in the top four",
    "relegation_probability": "Probability of finishing in the bottom three",
    "points_p10": "10th percentile of simulated final points",
    "points_p90": "90th percentile of simulated final points",
    "matchweek": "Matchweek of the last played round when the forecast was made",
    "season": "Season start year (2026 = 2026-27)",
    "model_version": "Forecasting model that produced the row (e.g. blend_v3)",
    "scored_at": "When the forecast was written",
    "match_id": "football-data.org match id (joins to bronze.raw_matches.id)",
    "matchday": "Matchweek the fixture belongs to",
    "utc_date": "Kick-off time (UTC)",
    "home_team_name": "Canonical home team name",
    "away_team_name": "Canonical away team name",
    "p_home": "Forecast probability of a home win",
    "p_draw": "Forecast probability of a draw",
    "p_away": "Forecast probability of an away win",
    "predicted_at": "When the (latest) forecast was written; frozen once the match is played",
}


def python_tables() -> dict[str, tuple[str, list[str]]]:
    """Gold tables written by Python: name -> (description, columns)."""
    sys.path.insert(0, str(ROOT))
    from planalyst.ml import predict

    return {
        "gold.gold_title_predictions": (
            "Latest title-race forecast, replaced on every run of the matchweek pipeline.",
            predict.PREDICTION_COLUMNS + ["matchweek", "season", "model_version"],
        ),
        "gold.title_prediction_history": (
            "Append-only: one set of rows per scored matchweek and model version, so the forecast "
            "can be audited as the season unfolds.",
            predict.HISTORY_COLUMNS + ["scored_at"],
        ),
        "gold.fixture_predictions": (
            "Forecast for every fixture. Refreshed until kick-off, then frozen, so live accuracy "
            "is judged on what was predicted beforehand.",
            predict.FIXTURE_COLUMNS + ["predicted_at"],
        ),
    }


def _yaml(path: Path) -> dict:
    return yaml.safe_load(path.read_text(encoding="utf-8")) or {}


def _table(rows: list[tuple[str, str]]) -> list[str]:
    lines = ["| Column | Description |", "|---|---|"]
    lines += [f"| `{name}` | {desc.replace('|', '/')} |" for name, desc in rows]
    return lines + [""]


def build() -> str:
    out = [
        "# Data dictionary",
        "",
        "_Generated by `python scripts/generate_data_dictionary.py` from the dbt schema files and "
        "the Gold tables written by Python; do not edit by hand._",
        "",
        "Layers: **bronze** (raw, loaded by dlt) -> **silver** (cleaned views and scored articles) "
        "-> **gold** (facts, dimensions and forecasts). dbt materialises silver/gold into the "
        "`public_silver` / `public_gold` schemas; Python writes `silver.silver_sentiment_scores` "
        "and the `gold` forecast tables.",
        "",
    ]

    sources = _yaml(MODELS / "sources.yml")
    out += ["## Bronze and scored sources", ""]
    for source in sources.get("sources", []):
        for table in source.get("tables", []):
            out += [f"### `{source['schema']}.{table['name']}`", "", table.get("description", ""), ""]
            out += _table([(c["name"], c.get("description", "")) for c in table.get("columns", [])])

    for layer in ("silver", "gold"):
        schema = _yaml(MODELS / layer / "schema.yml")
        out += [f"## {layer.capitalize()} models (`public_{layer}`)", ""]
        for model in schema.get("models", []):
            description = " ".join(str(model.get("description", "")).split())
            out += [f"### `{model['name']}`", "", description, ""]
            rows = [(c["name"], " ".join(str(c.get("description", "")).split())) for c in model.get("columns", [])]
            undocumented = [name for name, desc in rows if not desc]
            if undocumented:
                raise SystemExit(f"{model['name']}: add descriptions in schema.yml for {undocumented}")
            out += _table(rows)

    out += ["## Forecast tables written by Python (`gold`)", ""]
    for name, (description, columns) in python_tables().items():
        missing = [c for c in columns if c not in PYTHON_COLUMNS]
        if missing:
            raise SystemExit(f"{name}: add descriptions for columns {missing} to PYTHON_COLUMNS")
        out += [f"### `{name}`", "", description, ""]
        out += _table([(c, PYTHON_COLUMNS[c]) for c in columns])

    return "\n".join(out).rstrip("\n") + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the file is out of date")
    args = parser.parse_args()
    text = build()
    if args.check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current.replace("\r\n", "\n") != text:
            print("docs/data_dictionary.md is out of date; run scripts/generate_data_dictionary.py")
            return 1
        return 0
    OUTPUT.write_text(text, encoding="utf-8")
    print(f"Wrote {OUTPUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
